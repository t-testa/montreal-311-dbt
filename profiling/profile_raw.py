"""Profile raw.requetes311 and write docs/profiling.md.

Usage:  python profiling/profile_raw.py
"""
import os
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parent.parent
DB_PATH = Path(os.environ.get("MONTREAL_311_DB", ROOT / "data" / "montreal_311.duckdb"))
OUT = ROOT / "docs" / "profiling.md"
TABLE = "raw.requetes311"

# Plain-English guesses; column names are French.
MEANING = {
    "ID_UNIQUE": "Unique request ID (`YY-NNNNNN`, sometimes with `-A`/`-B` suffix). Null for 'Information' contacts.",
    "NATURE": "Nature of the contact: Requete (service request), Information, Plainte (complaint), Commentaire (comment).",
    "ACTI_NOM": "Activity name: the service/topic of the request (e.g. 'Collecte de déchets').",
    "TYPE_LIEU_INTERV": "Type of intervention location: Adresse, Intersection, Troncon (street segment), Installation (facility).",
    "RUE": "Street name of the location.",
    "RUE_INTERSECTION1": "First cross street (for Intersection locations).",
    "RUE_INTERSECTION2": "Second cross street (for Intersection locations).",
    "LOC_ERREUR_GDT": "Geocoding error flag from the city's geographic database (GDT): 1 = location error.",
    "ARRONDISSEMENT": "Borough (or reconciled municipality) as recorded on the request.",
    "ARRONDISSEMENT_GEO": "Borough derived from the geocoded coordinates (may differ from ARRONDISSEMENT).",
    "LIN_CODE_POSTAL": "Postal code of the location.",
    "DDS_DATE_CREATION": "Request creation timestamp (local time, no timezone).",
    "PROVENANCE_ORIGINALE": "Original channel the request came through (Téléphone, Personne, Mobile, ...).",
    "PROVENANCE_TELEPHONE": "Count of contacts received by telephone for this request.",
    "PROVENANCE_COURRIEL": "Count of contacts received by email.",
    "PROVENANCE_PERSONNE": "Count of contacts received in person.",
    "PROVENANCE_COURRIER": "Count of contacts received by postal mail.",
    "PROVENANCE_TELECOPIEUR": "Count of contacts received by fax.",
    "PROVENANCE_INSTANCE": "Count of contacts received via a municipal body/council (instance).",
    "PROVENANCE_MOBILE": "Count of contacts received via the mobile app.",
    "PROVENANCE_MEDIASOCIAUX": "Count of contacts received via social media.",
    "PROVENANCE_SITEINTERNET": "Count of contacts received via the website.",
    "UNITE_RESP_PARENT": "Parent organizational unit responsible for the request.",
    "LOC_LONG": "Longitude (WGS84).",
    "LOC_LAT": "Latitude (WGS84).",
    "LOC_X": "X coordinate (projected, MTM zone 8).",
    "LOC_Y": "Y coordinate (projected, MTM zone 8).",
    "DERNIER_STATUT": "Most recent status of the request (Terminée, Refusée, Prise en charge, ...).",
    "DATE_DERNIER_STATUT": "Timestamp of the most recent status change.",
}
DATE_COLS = {"DDS_DATE_CREATION", "DATE_DERNIER_STATUT"}


def md(v) -> str:
    return str(v).replace("|", "\\|").replace("\n", " ")


def main() -> None:
    con = duckdb.connect(str(DB_PATH), read_only=True)
    one = lambda sql: con.execute(sql).fetchone()[0]  # noqa: E731

    total = one(f"SELECT count(*) FROM {TABLE}")
    log = con.execute(
        "SELECT loaded_at, row_count, file_bytes FROM raw._load_log ORDER BY loaded_at DESC LIMIT 1"
    ).fetchone()
    cols = [r[0] for r in con.execute(f"DESCRIBE {TABLE}").fetchall()]

    lines = [
        "# Raw data profile: `raw.requetes311`",
        "",
        "_Generated by `profiling/profile_raw.py`. All columns are loaded as text; no casting applied._",
        "",
        f"- **Rows:** {total:,}",
        f"- **Columns:** {len(cols)}",
        f"- **Loaded at (UTC):** {log[0]}",
        f"- **Source file size:** {log[2] / 1e6:,.1f} MB",
        "",
        "## Columns",
        "",
        "| # | Column | Meaning (guess) | Null % | Distinct | Example values (top 5) | Min / Max |",
        "|---|--------|-----------------|-------:|---------:|------------------------|-----------|",
    ]
    for i, col in enumerate(cols, 1):
        q = f'"{col}"'
        nn, d = con.execute(f"SELECT count({q}), count(DISTINCT {q}) FROM {TABLE}").fetchone()
        ex = [
            r[0]
            for r in con.execute(
                f"SELECT {q} FROM {TABLE} WHERE {q} IS NOT NULL GROUP BY 1 ORDER BY count(*) DESC, 1 LIMIT 5"
            ).fetchall()
        ]
        rng = ""
        if col in DATE_COLS:
            lo, hi = con.execute(f"SELECT min({q}), max({q}) FROM {TABLE}").fetchone()
            rng = f"{lo} / {hi}"
        lines.append(
            f"| {i} | `{col}` | {md(MEANING.get(col, ''))} | {100 * (total - nn) / total:.1f} | {d:,} "
            f"| {md('; '.join(f'`{e}`' for e in ex))} | {rng} |"
        )

    # ---- key / duplicate checks -------------------------------------------------
    id_nn, id_d = con.execute(
        f"SELECT count(ID_UNIQUE), count(DISTINCT ID_UNIQUE) FROM {TABLE}"
    ).fetchone()
    info_null_id = one(f"SELECT count(*) FROM {TABLE} WHERE ID_UNIQUE IS NULL AND NATURE='Information'")
    other_null_id = one(f"SELECT count(*) FROM {TABLE} WHERE ID_UNIQUE IS NULL AND NATURE<>'Information'")
    suffixed = one(f"SELECT count(*) FROM {TABLE} WHERE regexp_matches(ID_UNIQUE, '-[A-Z]$')")
    base_d = one(
        f"SELECT count(DISTINCT regexp_replace(ID_UNIQUE, '-[A-Z]$', '')) FROM {TABLE}"
    )
    all_cols = ", ".join(f'"{c}"' for c in cols)
    dup_groups, dup_extra = con.execute(
        f"SELECT count(*), coalesce(sum(n - 1), 0) FROM (SELECT count(*) n FROM {TABLE} GROUP BY {all_cols} HAVING count(*) > 1)"
    ).fetchone()
    dup_by_nature = con.execute(
        f"SELECT NATURE, sum(n - 1) FROM (SELECT NATURE, count(*) n FROM {TABLE} GROUP BY {all_cols} HAVING count(*) > 1) GROUP BY 1 ORDER BY 2 DESC"
    ).fetchall()
    early_ids = one(f"SELECT count(*) FROM {TABLE} WHERE ID_UNIQUE LIKE '20-%' OR ID_UNIQUE LIKE '21-%'")
    arr_mismatch = one(
        f"""SELECT count(*) FROM {TABLE} WHERE ARRONDISSEMENT IS NOT NULL AND ARRONDISSEMENT_GEO IS NOT NULL
            AND replace(ARRONDISSEMENT, ' - ', '-') <> ARRONDISSEMENT_GEO"""
    )
    arr_fmt = one(f"SELECT count(*) FROM {TABLE} WHERE ARRONDISSEMENT LIKE '% - %'")
    arr_sentinel = con.execute(
        f"SELECT ARRONDISSEMENT, count(*) FROM {TABLE} WHERE ARRONDISSEMENT IN ('Ville de Montréal','Extérieur de Montréal') GROUP BY 1 ORDER BY 2 DESC"
    ).fetchall()
    ws = one(f"SELECT count(*) FROM {TABLE} WHERE RUE <> trim(RUE) OR ACTI_NOM <> trim(ACTI_NOM)")
    case_dups = con.execute(
        f"SELECT lower(ACTI_NOM), string_agg(DISTINCT ACTI_NOM, ' vs ') FROM {TABLE} GROUP BY 1 HAVING count(DISTINCT ACTI_NOM) > 1"
    ).fetchall()
    bad_pc = con.execute(
        f"SELECT LIN_CODE_POSTAL FROM {TABLE} WHERE LIN_CODE_POSTAL IS NOT NULL AND NOT regexp_matches(LIN_CODE_POSTAL, '^[A-Z][0-9][A-Z][0-9][A-Z][0-9]$')"
    ).fetchall()
    geo_err = one(f"SELECT count(*) FROM {TABLE} WHERE LOC_ERREUR_GDT = '1'")
    prov_null = one(f"SELECT count(*) FROM {TABLE} WHERE PROVENANCE_ORIGINALE IS NULL")
    same_ts = one(
        f"SELECT count(*) FROM {TABLE} WHERE DATE_DERNIER_STATUT = DDS_DATE_CREATION AND NATURE <> 'Information'"
    )
    geo_null_non_info = one(f"SELECT count(*) FROM {TABLE} WHERE LOC_LAT IS NULL AND NATURE <> 'Information'")
    no_addr = one(f"SELECT count(*) FROM {TABLE} WHERE NATURE <> 'Information' AND TYPE_LIEU_INTERV IS NULL")

    pct = lambda n: f"{100 * n / total:.1f}%"  # noqa: E731
    lines += [
        "",
        "## Likely primary key",
        "",
        f"`ID_UNIQUE` is unique among its {id_nn:,} non-null values ({id_d:,} distinct, 0 duplicates) but is "
        f"**null on {info_null_id:,} rows ({pct(info_null_id)})**, all with `NATURE = 'Information'`. "
        f"No non-Information row lacks an ID ({other_null_id:,}). So `ID_UNIQUE` is the natural key for "
        "Requete / Plainte / Commentaire rows, while Information rows have no key at all and would need a "
        "surrogate key (e.g. hash of all columns plus a row number) if they are kept.",
        "",
        "## Data quality issues",
        "",
        f"1. **Missing key for {pct(info_null_id)} of rows.** `ID_UNIQUE` is null on all {info_null_id:,} "
        "'Information' contacts (and they also have no `DERNIER_STATUT`, location or borough). "
        f"Only {id_nn:,} rows can be identified.",
        f"2. **Exact duplicate rows.** {dup_groups:,} distinct row patterns repeat, {dup_extra:,} surplus "
        f"rows in total ({', '.join(f'{n}: {int(c):,}' for n, c in dup_by_nature)}). "
        "Rows with an ID are unique, so the duplicates are keyless rows that cannot be told apart "
        "from genuine repeat calls.",
        f"3. **ID format is not uniform.** {suffixed:,} IDs carry an `-A`/`-B` suffix ({id_d:,} distinct IDs "
        f"collapse to {base_d:,} once the suffix is stripped), and ID lengths range from 4 to 11 characters. "
        f"{early_ids:,} IDs start with `20-`/`21-` even though all rows are created in 2022 or later.",
        f"4. **Two borough columns that disagree and use different formats.** `ARRONDISSEMENT` writes "
        f"`Mercier - Hochelaga-Maisonneuve` ({arr_fmt:,} rows use ` - `) while `ARRONDISSEMENT_GEO` writes "
        f"`Mercier-Hochelaga-Maisonneuve`. After normalizing that, {arr_mismatch:,} rows still disagree "
        "(e.g. recorded Ville-Marie vs geocoded Le Plateau-Mont-Royal). `ARRONDISSEMENT` also contains "
        "non-borough values: "
        + ", ".join(f"`{n}` ({c:,})" for n, c in arr_sentinel)
        + "; and 35 distinct values include reconciled suburbs (Westmount, Dorval, ...). "
        "`ARRONDISSEMENT_GEO` has no 'Extérieur' value.",
        f"5. **Sentinel-like / semantically null structure.** Null % is ~45.5-45.6 for location, borough and "
        f"status columns because of Information rows, yet {geo_null_non_info:,} non-Information rows lack "
        f"coordinates and {no_addr:,} have no `TYPE_LIEU_INTERV`. `LOC_ERREUR_GDT = 1` flags "
        f"{geo_err:,} geocoding errors. {same_ts:,} non-Information rows have "
        "`DATE_DERNIER_STATUT = DDS_DATE_CREATION` (never updated).",
        f"6. **Inconsistent casing / whitespace / format.** "
        + (
            f"Case variants of one activity: {', '.join(f'`{v}`' for _, v in case_dups)}. "
            if case_dups
            else ""
        )
        + f"{ws:,} rows have leading/trailing whitespace in `RUE` or `ACTI_NOM`. "
        + (
            f"Postal codes: {len(bad_pc)} not matching `A1A1A1` ({', '.join(f'`{p[0]}`' for p in bad_pc[:3])}). "
            if bad_pc
            else ""
        )
        + "Postal codes have no space (`H2L3A7`).",
        f"7. **`PROVENANCE_*` columns are counts, not flags.** Values go up to 60 per row, despite looking like "
        f"0/1 channel flags; `PROVENANCE_ORIGINALE` is null on {prov_null:,} rows.",
        "8. **Timestamps are ISO strings without a timezone** (`2023-07-10T20:15:39`, always 19 chars). "
        "All-text storage means dates, coordinates and counts all need explicit casting in staging.",
        "9. **Sparse intersection/street fields.** `RUE_INTERSECTION1/2` are 91.8% null and `RUE` is "
        "52.9% null; which street fields are filled depends on `TYPE_LIEU_INTERV`.",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
